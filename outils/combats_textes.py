"""Fiche Pokémon des combats : génère MonsutaPotaru/Services/Battle/BattleDexData.cs.

- Descriptions françaises des talents et des capacités : textes des jeux rassemblés par PokéAPI
  (https://github.com/PokeAPI/pokeapi, data/v2/csv). On prend le texte du plus ancien jeu qui en a un en français, le
  plus proche des règles de la génération des combats : Rubis/Saphir pour 70 des 76 talents (Noir/Blanc pour les six
  autres), Noir/Blanc pour toutes les capacités (PokéAPI n'a pas leurs textes français d'avant).
- Catégorie, puissance et précision des capacités : celles de la génération des combats, lues dans le simulateur
  installé (showdown/node_modules, @pkmn/sim), pour afficher ce que le combat applique vraiment.

Usage : python outils/combats_textes.py [génération, 3 par défaut]
À relancer quand une nouvelle génération a ses combats (BattleTeam.Format).
"""
import csv
import io
import json
import os
import re
import subprocess
import sys
import urllib.request

CSV = 'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/'
FRENCH = '5'  # languages.csv

# Ce que le simulateur sait de la génération : numéros des talents, et par capacité sa catégorie, sa puissance et sa
# précision (0 : n'échoue jamais, ou sans objet).
DUMP = r"""
const {Dex} = require('@pkmn/sim');
const dex = Dex.mod('gen' + process.argv[1]);
const moves = {};
for (const m of dex.moves.all()) {
  if (m.num < 1 || m.gen > dex.gen || m.isNonstandard || m.id.startsWith('hiddenpower') && m.id !== 'hiddenpower') continue;
  moves[m.num] = [m.category, m.basePower, m.accuracy === true ? 0 : m.accuracy];
}
const abilities = dex.abilities.all().filter(a => a.num > 0 && a.gen <= dex.gen).map(a => a.num);
console.log(JSON.stringify({moves, abilities}));
"""


def texts(name, key):
    """Texte français de chaque numéro, pris dans le plus ancien groupe de versions qui en a un."""
    with urllib.request.urlopen(CSV + name, timeout=60) as response:
        rows = csv.DictReader(io.StringIO(response.read().decode('utf-8')))
        best = {}
        for row in rows:
            if row['language_id'] != FRENCH:
                continue
            number, group = int(row[key]), int(row['version_group_id'])
            if number not in best or group < best[number][0]:
                best[number] = (group, clean(row['flavor_text']))
    return {number: text for number, (_, text) in best.items()}


def clean(text):
    """Une seule ligne : les retours à la ligne du jeu deviennent des espaces (un mot coupé est recollé)."""
    text = text.replace('­\n', '').replace('­', '')
    text = re.sub(r'\s+', ' ', text).strip()
    return re.sub(r' ([!?:;])', ' \\1', text)  # espace insécable avant la ponctuation haute


def cs(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    generation = sys.argv[1] if len(sys.argv) > 1 else '3'
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    dump = json.loads(subprocess.run(['node', '-e', DUMP, generation], cwd=os.path.join(root, 'showdown'),
                                     check=True, capture_output=True, text=True, encoding='utf-8').stdout)
    moves = {int(n): v for n, v in dump['moves'].items()}
    abilities = texts('ability_flavor_text.csv', 'ability_id')
    descriptions = texts('move_flavor_text.csv', 'move_id')
    missing = [f'talent {n}' for n in dump['abilities'] if n not in abilities] + \
              [f'capacité {n}' for n in moves if n not in descriptions]
    if missing:
        print('Sans description française : ' + ', '.join(missing))

    lines = ['// <auto-generated>',
             "// Généré par outils/combats_textes.py : descriptions françaises de PokéAPI (textes des jeux : le plus ancien qui en a",
             f'// un), catégorie, puissance et précision de la {generation}e génération lues dans le simulateur (@pkmn/sim). Ne pas',
             '// modifier à la main, changer le script et le relancer.',
             '// </auto-generated>',
             '',
             'namespace MonsutaPotaru.Services;',
             '',
             'public static class BattleDexData',
             '{',
             '    /// <summary>Description de chaque talent, par numéro national (vide : pas de talent de ce numéro).</summary>',
             '    public static readonly string[] Abilities =',
             '    [']
    for n in range(max(dump['abilities']) + 1):
        lines.append(f'        {cs(abilities.get(n, "") if n in dump["abilities"] else "")},')
    lines += ['    ];',
              '',
              '    /// <summary>Chaque capacité, par numéro national : catégorie, puissance, précision (0 : sans objet), description.</summary>',
              '    public static readonly BattleMoveData[] Moves =',
              '    [']
    for n in range(max(moves) + 1):
        category, power, accuracy = moves.get(n, ('Status', 0, 0))
        lines.append(f'        new(BattleMoveCategory.{category}, {power}, {accuracy}, {cs(descriptions.get(n, "") if n in moves else "")}),')
    lines += ['    ];', '}']
    out = os.path.join(root, 'MonsutaPotaru', 'Services', 'Battle', 'BattleDexData.cs')
    with open(out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('﻿' + '\n'.join(lines) + '\n')
    print(f'{len(dump["abilities"])} talents, {len(moves)} capacités : {out}')


if __name__ == '__main__':
    main()
